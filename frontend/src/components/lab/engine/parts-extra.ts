/**
 * The parts added for the full student list. Pins sit on schematic spacing; each `body` box covers the symbol so
 * selection, overlap checks and the fab-view outline line up with what is drawn.
 */

const row = (ids: string[], x0: number, y: number, step = 1): PinDef[] => ids.map((id, i) => ({ id, label: id, x: x0 + i * step, y }));
const col = (ids: string[], x: number, y0: number, step = 1): PinDef[] => ids.map((id, i) => ({ id, label: id, x, y: y0 + i * step }));
const two = (a: string, b: string, al = a, bl = b): PinDef[] => [
  { id: a, label: al, x: 0, y: 0 },
  { id: b, label: bl, x: 4, y: 0 },
];
const upright = (a: string, b: string, al = a, bl = b): PinDef[] => [
  { id: a, label: al, x: 0, y: 0 },
  { id: b, label: bl, x: 0, y: 4 },
];
/** Inline three-lead transistors: emitter/source, base/gate, collector/drain. */
const trio = (a: string, b: string, c: string): PinDef[] => row([a, b, c], 0, 0);

